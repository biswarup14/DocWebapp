import {
  SITE_URL,
  PREVIOUS_SITE_URL,
  CANONICAL_ALIASES,
  HOST_REDIRECTS_CONFIRMED,
  LAST_MODIFIED,
  INDEXABLE_ROUTES,
  DISALLOWED_PATHS,
  absoluteUrl,
  absoluteAssetUrl,
} from '../src/config/site.js';

/** Token replaced in index.html. Must not collide with Vite's `%VAR%` syntax. */
const SITE_URL_TOKEN = '__SITE_URL__';

function escapeXml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

function renderSitemap() {
  const urls = INDEXABLE_ROUTES.map((route) => {
    const images = route.images.length
      ? `\n${route.images
          .map(
            (image) => `    <image:image>
      <image:loc>${escapeXml(absoluteAssetUrl(image.src))}</image:loc>
      <image:title>${escapeXml(image.title)}</image:title>
    </image:image>`,
          )
          .join('\n')}`
      : '';

    return `  <url>
    <loc>${escapeXml(absoluteUrl(route.path))}</loc>
    <lastmod>${LAST_MODIFIED}</lastmod>
    <changefreq>${route.changefreq}</changefreq>
    <priority>${route.priority}</priority>${images}
  </url>`;
  }).join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${urls}
</urlset>
`;
}

function renderRobots() {
  const disallows = DISALLOWED_PATHS.map((path) => `Disallow: ${path}`).join('\n');

  return `User-agent: *
Allow: /

${disallows}

Sitemap: ${absoluteUrl('/sitemap.xml')}
`;
}

/**
 * Path-scoped 301s only.
 *
 * Workers Static Assets does NOT support domain-level redirects in this file
 * (see https://developers.cloudflare.com/workers/static-assets/redirects/ —
 * "Domain-level redirects" is listed as unsupported). A rule whose *source*
 * is an absolute URL naming another host is therefore silently ignored, which
 * would make a migration look handled when it is not. Host-level moves
 * (PREVIOUS_SITE_URL, CANONICAL_ALIASES) belong in a zone-level Cloudflare
 * rule on the domain being retired — see docs/DOMAIN-MIGRATION.md — so
 * assertHostsAreHandled() shouts at build time instead of pretending.
 *
 * Trailing-slash normalisation deliberately has no rule here. It is owned by
 * `html_handling: "drop-trailing-slash"` in wrangler.jsonc, which is the only
 * place that redirect actually runs — the assets layer answers /services/ from
 * disk before this file is consulted. Emitting a 301 here too would leave two
 * owners of one redirect, and the file's version would be dead config that
 * reads as though it were the real one.
 */
function renderRedirects() {
  return [
    '# Generated by build/seo-assets.js from src/config/site.js. Do not edit.',
    '# Path-scoped rules only: Workers Static Assets ignores domain-level',
    '# redirects in this file. Host moves are configured in Cloudflare.',
    '#',
    '# No trailing-slash rules on purpose — see renderRedirects() in',
    '# build/seo-assets.js. `html_handling: "drop-trailing-slash"` in',
    '# wrangler.jsonc owns that redirect, so /services/ -> /services.',
  ].join('\n').concat('\n');
}

/**
 * A host-level redirect recorded in src/config/site.js is documentation, not a
 * working redirect. Fail the build until it is explicitly acknowledged, so a
 * migration cannot be deployed while quietly dropping the old domain's ranking
 * signal.
 */
function assertHostRedirectsHandled() {
  const hosts = [
    ...(PREVIOUS_SITE_URL ? [PREVIOUS_SITE_URL] : []),
    ...CANONICAL_ALIASES,
  ];

  if (hosts.length === 0 || HOST_REDIRECTS_CONFIRMED) return;

  const rules = hosts
    .flatMap((host) => [
      `  source  ${host}/*`,
      `  target  ${SITE_URL}/:splat`,
      `  status  301`,
      '',
      `  source  ${host}`,
      `  target  ${SITE_URL}/`,
      `  status  301`,
    ])
    .join('\n');

  throw new Error(
    [
      `seo-assets: host redirect needed but not confirmed.`,
      '',
      `  moving from  ${hosts.join(', ')}`,
      `  moving to    ${SITE_URL}`,
      '',
      'Cloudflare Workers Static Assets does not support domain-level',
      'redirects in _redirects, so the rule above cannot live in this repo.',
      'Add it at zone level on the retired domain:',
      '',
      '  Cloudflare dashboard > retired domain > Rules > Bulk Redirects',
      '',
      rules,
      'Then verify each hop (301, single hop, correct target):',
      '',
      `  curl -IL ${hosts[0]}/services`,
      `  curl -IL ${hosts[0]}/`,
      '',
      'Once that is live, set HOST_REDIRECTS_CONFIRMED = true in',
      'src/config/site.js to unblock the build. Full checklist:',
      'docs/DOMAIN-MIGRATION.md',
    ].join('\n'),
  );
}

/**
 * Derives every public URL-bearing file from src/config/site.js:
 *   index.html  — swaps the __SITE_URL__ token
 *   sitemap.xml — generated from INDEXABLE_ROUTES
 *   robots.txt  — generated, with the sitemap pointer
 *   _redirects  — generated path-scoped 301s (trailing slashes)
 *
 * Previously these were hand-maintained copies that had already drifted from
 * src/components/SEO/SEO.jsx, which is how the old domain ended up hardcoded
 * in eight files.
 */
export function seoAssets() {
  return {
    name: 'docwebapp:seo-assets',
    enforce: 'pre',

    configResolved(config) {
      // Only gate the deploy artifact. `npm test` and `npm run dev` also
      // resolve this config, and blocking those would make it impossible to
      // run the test suite while a migration is in flight.
      if (config.command === 'build') assertHostRedirectsHandled();
    },

    transformIndexHtml: {
      order: 'pre',
      handler(html) {
        return html.replaceAll(SITE_URL_TOKEN, SITE_URL);
      },
    },

    generateBundle() {
      this.emitFile({
        type: 'asset',
        fileName: 'sitemap.xml',
        source: renderSitemap(),
      });

      this.emitFile({
        type: 'asset',
        fileName: 'robots.txt',
        source: renderRobots(),
      });

      this.emitFile({
        type: 'asset',
        fileName: '_redirects',
        source: renderRedirects(),
      });
    },
  };
}
